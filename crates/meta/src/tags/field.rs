//! The fields a tag key maps to, named after MusicBrainz Picard's internal tag names.

/// A field of [`TrackTags`](super::TrackTags), or a known field kept in its `extra` list.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) enum Field {
    Title,
    TitleSort,
    Subtitle,
    Artist,
    Artists,
    ArtistSort,
    Album,
    AlbumSort,
    AlbumArtist,
    AlbumArtists,
    AlbumArtistSort,
    /// A track number, possibly `n/total`.
    TrackNumber,
    TotalTracks,
    /// A disc number, possibly `n/total`.
    DiscNumber,
    TotalDiscs,
    DiscSubtitle,
    Date,
    /// A bare year (`YEAR`, APE `Year`); used when there is no full date.
    Year,
    OriginalDate,
    OriginalYear,
    ReleaseDate,
    Genre,
    Composer,
    ComposerSort,
    Conductor,
    Lyricist,
    Writer,
    Arranger,
    Remixer,
    Producer,
    Engineer,
    Mixer,
    DjMixer,
    /// A performer, possibly `Name (instrument)`.
    Performer,
    Label,
    CatalogNumber,
    Barcode,
    Isrc,
    Asin,
    ReleaseType,
    ReleaseStatus,
    ReleaseCountry,
    Media,
    Script,
    Language,
    MbRecordingId,
    MbTrackId,
    MbAlbumId,
    MbArtistId,
    MbAlbumArtistId,
    MbReleaseGroupId,
    MbWorkId,
    MbDiscId,
    AcoustidId,
    Comment,
    Lyrics,
    Compilation,
    Grouping,
    Work,
    Movement,
    /// A movement number, possibly `n/total`.
    MovementNumber,
    MovementTotal,
    ShowMovement,
    Bpm,
    Key,
    Mood,
    EncodedBy,
    EncoderSettings,
    Copyright,
    License,
    Website,
    Director,
    OriginalAlbum,
    OriginalArtist,
    ReplayGainTrackGain,
    ReplayGainTrackPeak,
    ReplayGainAlbumGain,
    ReplayGainAlbumPeak,
    R128TrackGain,
    R128AlbumGain,
    /// `RATING`: 0–5 or 0–100.
    Rating,
    /// `FMPS_RATING`: 0.0–1.0.
    FmpsRating,
    /// ASF `WM/SharedUserRating`: 0–99.
    WmpRating,
    /// A field that is never kept: encoder delay, iTunes normalization and such.
    Ignored,
}

